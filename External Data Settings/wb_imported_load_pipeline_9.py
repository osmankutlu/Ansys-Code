SKIP_BRANCH = ("Geometry", "Mesh", "Connections", "CoordinateSystems", "NamedSelections",
               "Solution", "Materials", "Part", "Body")


def find_groups(obj, out, depth=0):
    """Imported Load groups sit directly under an analysis, so heavy branches (geometry, mesh,
    connections, solution) are not walked - a full tree scan is slow on big models."""
    if depth > 3:
        return
    try:
        kids = list(obj.Children)
    except:
        kids = []
    for k in kids:
        try:
            tname = k.GetType().Name
        except:
            tname = ""
        if "ImportedLoadGroup" in tname:
            out.append(k)
        elif tname not in SKIP_BRANCH:
            find_groups(k, out, depth + 1)


def current_groups():
    out = []
    try:
        find_groups(ExtAPI.DataModel.Project.Model, out)
    except Exception as e:
        log_msg("Imported Load group scan failed: %s" % e)
    return out


def match_group(groups, letter):
    """Group named 'Imported Load (<cell>)', cell = External Data Setup cell (e.g. A2)."""
    if not letter:
        return None
    key = letter if letter[-1:].isdigit() else letter + "2"
    for i, g in enumerate(groups):
        try:
            if ("(%s)" % key) in g.Name:
                return i
        except:
            pass
    return None


def add_methods(group):
    names = []
    try:
        members = dir(group)
    except:
        members = []
    for m in members:
        if m.startswith("AddImported") and len(m) > len("AddImported"):
            names.append(m)
    names.sort()
    return names


def nice(m):
    return re.sub(r"([a-z0-9])([A-Z])", r"\1 \2", m[len("AddImported"):])


