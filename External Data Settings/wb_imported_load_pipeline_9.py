WINAPI_SRC = """
using System;
using System.Collections.Generic;
using System.Runtime.InteropServices;
using System.Text;
namespace WBTool {
  public static class WinApi {
    delegate bool EnumProc(IntPtr h, IntPtr l);
    [DllImport("user32.dll")] static extern bool SetForegroundWindow(IntPtr h);
    [DllImport("user32.dll")] static extern bool ShowWindow(IntPtr h, int cmd);
    [DllImport("user32.dll")] static extern bool IsIconic(IntPtr h);
    [DllImport("user32.dll")] static extern IntPtr GetForegroundWindow();
    [DllImport("user32.dll")] static extern bool IsWindowVisible(IntPtr h);
    [DllImport("user32.dll", CharSet = CharSet.Unicode)]
    static extern int GetWindowText(IntPtr h, StringBuilder sb, int max);
    [DllImport("user32.dll")] static extern uint GetWindowThreadProcessId(IntPtr h, out uint pid);
    [DllImport("user32.dll")] static extern bool EnumWindows(EnumProc cb, IntPtr l);
    [DllImport("user32.dll")] static extern void keybd_event(byte vk, byte scan, uint flags, UIntPtr extra);

    public static IntPtr[] FindWindows(uint pid, string titlePart) {
      List<IntPtr> res = new List<IntPtr>();
      EnumWindows(delegate(IntPtr h, IntPtr l) {
        uint p;
        GetWindowThreadProcessId(h, out p);
        if (p == pid && IsWindowVisible(h)) {
          StringBuilder sb = new StringBuilder(512);
          GetWindowText(h, sb, 512);
          string t = sb.ToString();
          if (t.Length > 0 && (titlePart == null ||
              t.IndexOf(titlePart, StringComparison.OrdinalIgnoreCase) >= 0)) res.Add(h);
        }
        return true;
      }, IntPtr.Zero);
      return res.ToArray();
    }

    public static bool BringToFront(IntPtr h) {
      if (IsIconic(h)) ShowWindow(h, 9);              // SW_RESTORE
      bool ok = SetForegroundWindow(h);
      if (GetForegroundWindow() != h) {               // foreground lock: press/release Alt, retry
        keybd_event(0x12, 0, 0, UIntPtr.Zero);
        ok = SetForegroundWindow(h);
        keybd_event(0x12, 0, 2, UIntPtr.Zero);
      }
      return GetForegroundWindow() == h;
    }
  }
}
"""


def get_winapi():
    try:
        from Microsoft.CSharp import CSharpCodeProvider
        from System.CodeDom.Compiler import CompilerParameters
        cp = CompilerParameters()
        cp.GenerateInMemory = True
        cp.ReferencedAssemblies.Add("System.dll")
        res = CSharpCodeProvider().CompileAssemblyFromSource(cp, WINAPI_SRC)
        if res.Errors.HasErrors:
            raise Exception(str(res.Errors[0]))
        clr.AddReference(res.CompiledAssembly)
        from WBTool import WinApi
        return WinApi
    except Exception as ex:
        log_msg("Window helper could not be compiled: %s" % ex)
        return None


def bring_wb_to_front(pid):
    """Bring the Workbench process `pid` to the foreground (restore it if minimized)."""
    api = get_winapi()
    if api is not None:
        try:
            hw = list(api.FindWindows(pid, "Workbench"))
            if not hw:
                from System.Diagnostics import Process
                mh = Process.GetProcessById(pid).MainWindowHandle
                if int(mh) != 0:
                    hw = [mh]
            if not hw:
                hw = list(api.FindWindows(pid, None))
            if hw:
                api.BringToFront(hw[0])
                return
        except Exception as ex:
            log_msg("Bring-to-front failed: %s" % ex)
