def read_result(path):
    res = {}
    try:
        f = codecs.open(path, "r", "utf-8")
        try:
            for ln in f.read().splitlines():
                if "=" in ln:
                    k, v = ln.split("=", 1)
                    res[k.strip()] = v.strip()
        finally:
            f.close()
    except Exception as e:
        log_msg("Could not read the Workbench result: %s" % e)
    return res


def finish_in_mechanical(res, groups):
    """Stage 2 (UI thread): insert the load and open the filler."""
    letter = res.get("ext_letter", "")
    pre = match_group(groups, letter)
    if pre is None and res.get("prefer_id") is not None:
        for i_, g_ in enumerate(groups):
            if group_id(g_) == res.get("prefer_id"):
                pre = i_
    if not groups:
        progress_close()
        MessageBox.Show(
            "The External Data is connected, but Mechanical does not show the Imported Load "
            "group yet.\n\nIn Workbench, right-click the Setup cell of the Mechanical system and "
            "choose Refresh / Update, then press 'Refresh' in the filler window.\n\nThe filler window opens now.",
            PIPELINE_TITLE)
        launch_filler()
        return
    if pre is None:
        pre = len(groups) - 1
        log_msg("No group named for cell %s; using the last one." % letter)
    progress_hide()
    choice = ask_load_kind(groups, pre)
    progress_show()
    if choice is None:
        progress_close()
        return
    group, method = choice
    progress("Inserting the Imported %s ..." % nice(method))
    try:
        ld = getattr(group, method)()
    except Exception as ex:
        progress_close()
        MessageBox.Show("Could not insert the load (%s):\n\n%s\n\nThe filler window opens now - "
                        "insert the load manually, then press Refresh." % (method, ex),
                        PIPELINE_TITLE)
        launch_filler()
        return
    try:
        ExtAPI.DataModel.Tree.Activate([ld])
    except:
        pass
    try:
        sid = ld.ObjectId
    except:
        sid = None
    progress("Opening the Imported Load Filler ...")
    launch_filler(select_id=sid)


def nm_of(g):
    try:
        return g.Name
    except:
        return "?"


def group_id(g):
    try:
        return g.ObjectId
    except:
        return None


def start_followup(job_path, result_path, status_path, base_ids):
    """Timer on the UI thread: shows what Workbench is doing, then continues in Mechanical."""
    st = {"stage": "wb", "tries": 0, "res": {}, "last": "", "t0": 0.0}
    progress_wb(status_path)
    tm = Timer()
    tm.Interval = 300
    _KEEP.append(tm)

    def on_tick(s, e):
        try:
            if st["stage"] == "wb":
                if not RUN["done"]:
                    return
                res = read_result(result_path)
                safe_remove(job_path)
                safe_remove(result_path)
                safe_remove(status_path)
                st["res"] = res
                if res.get("status", "") != "ok":
                    tm.Stop()
                    progress_close()
                    msg = res.get("message") or RUN["error"] or "The Workbench part did not finish."
                    MessageBox.Show(msg, PIPELINE_TITLE, MessageBoxButtons.OK, MessageBoxIcon.Warning)
                    return
                st["stage"] = "wait"
                st["t0"] = time.time()
                progress("Mechanical: looking for the Imported Load group of the new External Data ...")
                tm.Interval = 200
                return
            if st["stage"] == "wait":
                st["tries"] += 1
                if st["tries"] % 5 == 0:
                    try:
                        ExtAPI.DataModel.Tree.Refresh()      # make Mechanical notice the new group
                    except:
                        pass
                t1 = time.time()
                groups = current_groups()
                dt = time.time() - t1
                letter = st["res"].get("ext_letter", "")
                found = match_group(groups, letter) is not None
                new = [g for g in groups if group_id(g) not in base_ids]
                if st["tries"] in (1, 10, 50, 100):
                    note("wait try %d: scan %.2f s, groups=%s, expected cell=%s, new=%d" % (
                        st["tries"], dt, [nm_of(g) for g in groups], letter, len(new)))
                if found or new or st["tries"] >= 150:
                    note("group %s after %.1f s (%d scans)" % (
                        "matched by name" if found else ("new group seen" if new else "NOT found - timeout"),
                        time.time() - st["t0"], st["tries"]))
                    if (not found) and new:
                        st["res"]["prefer_id"] = group_id(new[-1])
                    tm.Stop()
                    finish_in_mechanical(st["res"], groups)
        except Exception as ex:
            tm.Stop()
            progress_close()
            MessageBox.Show("Error after the Workbench step:\n\n%s" % ex, PIPELINE_TITLE)

    tm.Tick += on_tick
    tm.Start()


