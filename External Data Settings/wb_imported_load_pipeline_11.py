# One script that chains the two earlier tools:
#   mech_run_wb_tool_7 / wb_external_data_setup_16   (External Data setup in Workbench)
#   imported_load_filler_4                           (Imported Load table filler)
#
# Flow
#   1) A window asks for the input file(s): press Browse (.txt, .xlsx or .xls, several files
#      allowed), order them, then Continue.
#      Excel files are converted to a comma-separated .csv first (External Data cannot read
#      Excel directly); the header row is kept, spaces in header names become "_".
#   2) Workbench: a NEW External Data system is created and the file(s) are added.
#   3) The External Data pop-up opens (one tab per file): Start Import At Line, Length Unit,
#      Dimension (2D/3D), Delimiter Type (Comma / Semicolon / Space / Tab / User Defined),
#      Coordinate System Type, rigid-transformation units and the column table
#      (Data Type / Unit / Identifier). The delimiter is detected from the file (Tab if unsure)
#      and applied to Workbench at once; changing it rebuilds the column table.
#      "Start Import At Line" defaults to 1 (column headers stay visible in the preview).
#   4) A pop-up asks which Mechanical system's Setup cell the External Data is connected to
#      (TransferData, then Update + Refresh).
#   5) Back in Mechanical: the "Imported Load (<External Data cell>)" group is looked up
#      (it can take a few seconds to appear), a pop-up asks which load type to insert
#      (Displacement, Temperature, Pressure ... - taken from what the group offers),
#      the load is inserted and the Imported Load Filler window opens on it.
#
# Technical notes (same as mech_run_wb_tool_7)
#   - The Workbench part is embedded (base64), written to a temp file, run on the Workbench
#     project page through wbjn and deleted afterwards. The Workbench that OWNS this
#     Mechanical is brought to the front first.
#   - The Workbench windows are non-blocking; Mechanical stays usable.
