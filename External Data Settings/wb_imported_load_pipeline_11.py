def main_run():
    picked = pick_input_files()
    if not picked:
        return
    progress_open("Preparing the input file(s) ...")
    try:
        files, notes = prepare_files(picked)
    except Exception as ex:
        progress_close()
        MessageBox.Show("Could not prepare the input file(s):\n\n%s" % ex, PIPELINE_TITLE)
        return
    for n in notes:
        log_msg("Excel conversion: " + n)

    progress("Starting Workbench ...")
    base_ids = set([group_id(g) for g in current_groups()])
    folder = temp_folder()
    tag = uuid.uuid4().hex[:8]
    job_path = os.path.join(folder, "job_%s.txt" % tag)
    result_path = os.path.join(folder, "result_%s.txt" % tag)
    status_path = os.path.join(folder, "status_%s.txt" % tag)
    try:
        jf = codecs.open(job_path, "w", "utf-8")
        try:
            jf.write(u"\r\n".join(files) + u"\r\n")
        finally:
            jf.close()
        tool_path = write_temp_tool()
    except Exception as ex:
        progress_close()
        MessageBox.Show("Could not write the temporary files:\n\n%s" % ex, PIPELINE_TITLE)
        return

    # This text is executed on the Workbench side; the temp tool file is deleted when the tool ends.
    WB_CMDS = '''
import os
_tool = r"%s"
try:
    g = dict(globals())
    g["__file__"] = _tool
    g["PIPELINE_JOB"] = r"%s"
    g["PIPELINE_RESULT"] = r"%s"
    g["PIPELINE_STATUS"] = r"%s"
    execfile(_tool, g)
except Exception:
    import traceback, clr
    clr.AddReference("System.Windows.Forms")
    from System.Windows.Forms import MessageBox
    MessageBox.Show(traceback.format_exc(), "External Data Tool error")
finally:
    try:
        os.remove(_tool)
    except Exception:
        pass
''' % (tool_path, job_path, result_path, status_path)

    RUN["done"] = False
    RUN["error"] = None
    run_in_workbench(WB_CMDS, tool_path)
    start_followup(job_path, result_path, status_path, base_ids)


main_run()
