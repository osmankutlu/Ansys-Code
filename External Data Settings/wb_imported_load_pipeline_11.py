def _unesc(s):
    def num(m):
        try:
            if m.group(1) in ("x", "X"):
                return chr(int(m.group(2), 16)) if int(m.group(2), 16) < 128 else u" "
            return chr(int(m.group(2))) if int(m.group(2)) < 128 else u" "
        except Exception:
            return u" "
    s = re.sub(r"&#([xX]?)([0-9A-Fa-f]+);", num, s)
    return (s.replace("&lt;", "<").replace("&gt;", ">").replace("&quot;", '"')
             .replace("&apos;", "'").replace("&amp;", "&"))


def _zip_text(path, name):
    """Text of one entry of a zip (xlsx) file; None if the entry does not exist."""
    try:
        import zipfile
        z = zipfile.ZipFile(path, "r")
        try:
            return z.read(name).decode("utf-8")
        finally:
            z.close()
    except KeyError:
        return None
    except Exception:
        pass
    # fallback: .NET zip support
    clr.AddReference("System.IO.Compression")
    clr.AddReference("System.IO.Compression.FileSystem")
    from System.IO.Compression import ZipFile
    from System.IO import StreamReader
    from System.Text import UTF8Encoding
    arc = ZipFile.OpenRead(path)
    try:
        for ent in arc.Entries:
            if ent.FullName == name:
                sr = StreamReader(ent.Open(), UTF8Encoding(False))
                try:
                    return sr.ReadToEnd()
                finally:
                    sr.Close()
    finally:
        arc.Dispose()
    return None


def _col_idx(letters):
    n = 0
    for ch in letters:
        n = n * 26 + (ord(ch) - 64)
    return n - 1


def read_xlsx(path):
    """First worksheet of an .xlsx as a list of rows (list of strings). No Excel needed."""
    shared = []
    sx = _zip_text(path, "xl/sharedStrings.xml")
    if sx:
        for si in re.findall(r"<si\b[^>]*?(?:/>|>.*?</si>)", sx, re.S):
            parts = re.findall(r"<t\b[^>]*>(.*?)</t>", re.sub(r"<rPh\b.*?</rPh>", "", si, flags=re.S), re.S)
            shared.append(_unesc("".join(parts)))

    sheet_path = "xl/worksheets/sheet1.xml"
    try:
        wbx = _zip_text(path, "xl/workbook.xml")
        rels = _zip_text(path, "xl/_rels/workbook.xml.rels")
        tag = re.search(r"<sheet\b[^>]*>", wbx)
        rid = re.search(r'r:id="([^"]+)"', tag.group(0)).group(1)
        for rm in re.finditer(r"<Relationship\b[^>]*>", rels):
            t = rm.group(0)
            if re.search(r'\bId="%s"' % re.escape(rid), t):
                tgt = re.search(r'Target="([^"]+)"', t).group(1).lstrip("/")
                sheet_path = tgt if tgt.startswith("xl/") else "xl/" + tgt
                break
    except Exception:
        pass

    xml = _zip_text(path, sheet_path)
    if xml is None:
        raise ValueError("Worksheet not found in %s" % os.path.basename(path))

    rows = []
    for rm in re.finditer(r"<row\b[^>]*?(?:/>|>(.*?)</row>)", xml, re.S):
        body = rm.group(1)
        if not body:
            continue
        cells = {}
        for cm in re.finditer(r"<c\b([^>]*?)(?:/>|>(.*?)</c>)", body, re.S):
            attrs, inner = cm.group(1), cm.group(2) or ""
            ref = re.search(r'\br="([A-Z]+)\d+"', attrs)
            if not ref:
                continue
            ci = _col_idx(ref.group(1))
            tm = re.search(r'\bt="(\w+)"', attrs)
            typ = tm.group(1) if tm else "n"
            val = ""
            vm = re.search(r"<v>(.*?)</v>", inner, re.S)
            if typ == "s" and vm:
                try:
                    val = shared[int(vm.group(1))]
                except Exception:
                    val = ""
            elif typ == "inlineStr":
                val = _unesc("".join(re.findall(r"<t\b[^>]*>(.*?)</t>", inner, re.S)))
            elif typ == "e":
                val = ""
            elif vm:
                val = _unesc(vm.group(1))
            cells[ci] = val.strip()
        if cells:
            width = max(cells.keys()) + 1
            rows.append([cells.get(i, "") for i in range(width)])
    return rows


def read_xls(path):
    """Old binary .xls through Excel (COM). Needs Excel to be installed."""
    from System import Type, Activator
    from System.Runtime.InteropServices import Marshal
    t = Type.GetTypeFromProgID("Excel.Application")
    if t is None:
        raise ValueError("Excel is not installed - save '%s' as .xlsx and try again."
                         % os.path.basename(path))
    xl = Activator.CreateInstance(t)
    rows = []
    try:
        xl.Visible = False
        xl.DisplayAlerts = False
        wb = xl.Workbooks.Open(path)
        try:
            ws = wb.Sheets[1]
            vals = ws.UsedRange.Value2
            if isinstance(vals, System.Array):
                r0, r1 = vals.GetLowerBound(0), vals.GetUpperBound(0)
                c0, c1 = vals.GetLowerBound(1), vals.GetUpperBound(1)
                for r in range(r0, r1 + 1):
                    row = []
                    for c in range(c0, c1 + 1):
                        v = vals.GetValue(r, c)
                        if v is None:
                            row.append("")
                        elif isinstance(v, float):
                            row.append("%.15g" % v)
                        else:
                            row.append(str(v).strip())
                    rows.append(row)
            elif vals is not None:
                rows.append([str(vals)])
        finally:
            wb.Close(False)
    finally:
        try:
            xl.Quit()
            Marshal.ReleaseComObject(xl)
        except Exception:
            pass
    return rows


def _is_number(s):
    try:
        float(s.replace(",", "."))
        return True
    except Exception:
        return False


def rows_to_csv(rows, out_path):
    rows = [r for r in rows if any(c.strip() for c in r)]
    if not rows:
        raise ValueError("The sheet has no data.")
    width = max(len(r) for r in rows)
    rows = [list(r) + [""] * (width - len(r)) for r in rows]
    has_header = not all(_is_number(c) for c in rows[0] if c.strip())
    out = []
    for i, r in enumerate(rows):
        cells = []
        for j, c in enumerate(r):
            c = c.replace(",", " ").replace('"', "").replace("\r", " ").replace("\n", " ").strip()
            if i == 0 and has_header:
                c = re.sub(r"\s+", "_", c) or ("Col%d" % (j + 1))
            cells.append(c)
        out.append(",".join(cells))
    f = codecs.open(out_path, "w", "utf-8")
    try:
        f.write("\r\n".join(out) + "\r\n")
    finally:
        f.close()
    return len(rows), width, has_header


