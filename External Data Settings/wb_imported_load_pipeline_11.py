# ---------------------------------------------------------------- helpers
def S(v, n=300):
    try:
        s = str(v)
    except:
        s = "<str error>"
    return s.replace("\r", " ").replace("\n", " ")[:n]


def fmt(v):
    if isinstance(v, float):
        return "%g" % v
    return str(v)


def find_loads(obj, out):
    try:
        kids = list(obj.Children)
    except:
        kids = []
    for k in kids:
        try:
            tname = k.GetType().Name
        except:
            tname = ""
        if "Imported" in tname and tname != "ImportedLoadGroup":
            try:
                k.GetTableByName(TABLE_NAME)
                out.append(k)
            except:
                pass
        if tname not in ('Geometry', 'Mesh', 'Connections', 'CoordinateSystems', 'NamedSelections', 'Solution'):
            find_loads(k, out)


def load_label(o):
    try:
        par = o.Parent.Name.strip()
    except:
        par = "?"
    try:
        return "%s > %s  [%s]  (ID %s)" % (par, o.Name, o.GetType().Name, o.ObjectId)
    except:
        return S(o)


def classify_columns(t):
    """Returns [(name, 'dd'|'num', items)] ; 'dd' = dropdown (source) column."""
    info = []
    for i, c in enumerate(list(t.Columns)):
        items = None
        try:
            items = list(t.DropDownItems(i))
        except:
            items = None
        if items:
            info.append((str(c), "dd", items))
        else:
            info.append((str(c), "num", None))
    return info


def is_time(name):
    low = name.lower()
    return ("time" in low) or ("frequency" in low)


def num_default(name):
    if is_time(name) or "scale" in name.lower():
        return "1"
    return "0"


